// 블로그 제목 → Home 카드용 짧은 제목 (lib/blog-feed.mjs → functions/api/blog/에서 사용)
// 날짜·요일·기간, 장소 꼬리("in 순천"), 회차("(2편)"), 학교 이름 머리말을 지움.
// 예) "2024년 12월16일 독서캠프 in 순천" → "독서캠프"

const RULES = [
  // 날짜 범위·요일: "2022. 9월 29일(목) ~ 30일 (금)", "(9월30일 ~10월2일)"
  [/\(\s*\d[^)]*\)/g, " "],
  [/\d{4}\s*[.년]\s*(도\s*)?(\d{1,2}\s*[.월]\s*\d{1,2}\s*일)?/g, " "],
  [/\d{1,2}\s*월\s*\d{1,2}\s*일/g, " "],
  [/~\s*\d{1,2}\s*일?/g, " "],
  [/\(\s*[월화수목금토일]\s*\)/g, " "],
  [/\d+\s*박\s*\d+\s*일/g, " "],
  // 앞에 붙은 연도: "2022 중국어 수업", "25년 청미프"
  [/^\s*(\d{4}|\d{2}\s*년)\s+/, ""],
  // 날짜 줄임: "3.11 리더십 수업", "4/9일"
  [/(^|\s)\d{1,2}\s*[./]\s*\d{1,2}\s*일?(?=\s|$)/g, " "],
  // 장소 꼬리: "in 순천", "( in화순)", "In SEOUL"
  [/\(\s*in\s*[^)]*\)/gi, " "],
  [/\s+in\s*\S+\s*$/i, ""],
  // 회차·버전: "(2편)", "(1)", "(선배 ver.)"
  [/\(\s*(\d+\s*편?|[^)]*ver\.?)\s*\)\s*$/i, ""],
  // 학교 이름 머리말: "뉴젠리더십학교 _ 월호도 봉사활동", "뉴젠리더십기독대안학교 입학설명회"
  [/^\s*뉴젠\s*리더십\s*(기독)?\s*(대안)?\s*학교\s*[_\-:|]?\s*(?=\S)/, ""],
];

export function shortTitle(title) {
  let s = title;
  for (const [re, to] of RULES) s = s.replace(re, to);
  s = s.replace(/\s+/g, " ").replace(/^[\s~\-_|.,:]+|[\s~\-_|.,:]+$/g, "");
  // 다 지워져 버리면 원래 제목
  return s || title.trim();
}
